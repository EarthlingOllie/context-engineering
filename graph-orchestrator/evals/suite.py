def compose_yaml(cpus: int, memory: str) -> str:
    """The sandbox's compose file: the run's CPU count and memory are applied to the container."""
    return (
        "# Generated by dispatch_suite.py. The bridge runs inside the container on localhost,\n"
        "# so the sandbox needs no outbound network at run time.\n"
        "services:\n"
        "  default:\n"
        "    build:\n"
        f"      context: {EVALS / 'sandbox'}\n"
        "    image: dispatch-evals-sandbox:local\n"
        "    init: true\n"
        '    command: ["sleep", "infinity"]\n'
        "    network_mode: none\n"
        f"    cpus: {cpus}\n"
        f"    mem_limit: {memory}\n"
    )


def load_samples() -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted(SAMPLES.glob("*.json"))]


def fixture_sandbox_files(fixture: str) -> dict[str, Path]:
    """The files the solver copies into the sandbox for a fixture: sandbox path -> host file.

    Only `fixtures/<name>/sandbox/` is copied, to `/work/`. `fixtures/<name>/hidden/`
    holds the hidden check and is read on the host by the scorer only.
    """
    root = FIXTURES / fixture / "sandbox"
    return {f"/work/{p.relative_to(root).as_posix()}": p for p in sorted(root.rglob("*")) if p.is_file()}


def hidden_files(fixture: str) -> list[Path]:
    root = FIXTURES / fixture / "hidden"
    return sorted(p for p in root.rglob("*") if p.is_file())


def hidden_facts(fixture: str) -> list[dict]:
    return json.loads((FIXTURES / fixture / "hidden" / "planted_facts.json").read_text())


def hidden_check(sample: dict) -> dict:
    """The hidden check a sample is scored by, read on the host.

    The fixture's `hidden/expected_block.json` (or, for a research fixture, its
    planted facts) gives the check; the sample's own `check` may refine it
    (`source`: score the facts in the returned `result` only, or in the
    result and the files the agents wrote). A check's `unchanged` paths are
    resolved to the fixture's original text, which the files must still hold.
    """
    fixture = sample["fixture"]
    root = FIXTURES / fixture / "hidden"
    block = root / "expected_block.json"
    base = json.loads(block.read_text()) if block.exists() else {"kind": "facts"}
    check = {**base, **sample.get("check", {})}
    if check["kind"] == "facts":
        check.setdefault("source", "result+files")
        check["facts"] = hidden_facts(fixture)
    if "unchanged" in check:
        copied = fixture_sandbox_files(fixture)
        check["unchanged"] = {p: copied[p].read_text() for p in check["unchanged"]}
    return check
