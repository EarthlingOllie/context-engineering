// Bundles the TypeScript into the two plain JavaScript files the plugin ships.
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const META = `export const meta = {
  name: 'dispatch',
  description: 'graph-orchestrator: run one dispatch through its topology (single, generator-evaluator, fan-out, chain, relay, best-of-n, iterative-fan-out, panel, debate) and write its trace lines',
  whenToUse: 'Invoked by the graph-orchestrator skill once per dispatch, from a wrapper script that names the workflow, with { now, scratch, dispatch, humans } as args. Not for direct use.',
}
`;

const FOOTER = `
// --- script body: the harness supplies agent, parallel, log and args ---
return await runWorkflow(args, { agent, parallel, log });
`;

mkdirSync("workflows", { recursive: true });
mkdirSync("scripts", { recursive: true });

// 1. The dispatch script: one file, no imports, meta literal first, return last.
const bundle = await build({
  entryPoints: ["src/entry.ts"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2020",
  write: false,
  legalComments: "none",
});
let js = bundle.outputFiles[0].text;
js = js.replace(/\nexport \{[^}]*\};?\s*$/, "\n");
if (/^\s*(import|export)\b/m.test(js)) throw new Error("dispatch bundle still contains an import or export");
if (/\brequire\(/.test(js)) throw new Error("dispatch bundle contains require()");
if (!/\bfunction runWorkflow\b/.test(js)) throw new Error("dispatch bundle lost runWorkflow");
writeFileSync("workflows/dispatch.js", META + "\n// Generated by build.mjs from src/ — do not edit.\n" + js + FOOTER);

// 2. The trace renderer CLI: a Node script.
await build({
  entryPoints: ["src/trace/cli.ts"],
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  outfile: "scripts/render-trace.js",
  banner: { js: "#!/usr/bin/env node\n// Generated by build.mjs from src/trace — do not edit." },
  legalComments: "none",
});

console.log("built workflows/dispatch.js and scripts/render-trace.js");
