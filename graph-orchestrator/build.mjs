// Bundles the TypeScript into the two plain JavaScript files the plugin ships.
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const META = `export const meta = {
  name: 'wave',
  description: 'graph-orchestrator: run one wave of dispatches (single, generator-evaluator, fan-out, chain) and write the trace',
  whenToUse: 'Invoked by the graph-orchestrator skill once per wave with { now, traceFile, maxAgents, dispatches } as args. Not for direct use.',
  phases: [{ title: 'scribe', detail: 'append the wave events to the trace file' }],
}
`;

const FOOTER = `
// --- script body: the harness supplies agent, parallel, log and args ---
return await runWave(args, { agent, parallel, log });
`;

mkdirSync("workflows", { recursive: true });
mkdirSync("scripts", { recursive: true });

// 1. The wave script: one file, no imports, meta literal first, return last.
const wave = await build({
  entryPoints: ["src/entry.ts"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2020",
  write: false,
  legalComments: "none",
});
let js = wave.outputFiles[0].text;
js = js.replace(/\nexport \{[^}]*\};?\s*$/, "\n");
if (/^\s*(import|export)\b/m.test(js)) throw new Error("wave bundle still contains an import or export");
if (/\brequire\(/.test(js)) throw new Error("wave bundle contains require()");
if (!/\bfunction runWave\b|\basync function runWave\b/.test(js)) throw new Error("wave bundle lost runWave");
writeFileSync("workflows/wave.js", META + "\n// Generated by build.mjs from src/ — do not edit.\n" + js + FOOTER);

// 2. The trace renderer CLI: a Node script.
await build({
  entryPoints: ["src/trace/cli.ts"],
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  outfile: "scripts/render-trace.js",
  banner: { js: "#!/usr/bin/env node\n// Generated by build.mjs from src/trace — do not edit." },
  legalComments: "none",
});

console.log("built workflows/wave.js and scripts/render-trace.js");
