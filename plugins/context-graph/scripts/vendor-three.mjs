#!/usr/bin/env node
// Vendors the three.js math files the mod needs into vendor/three-math/.
// Usage: node scripts/vendor-three.mjs [path/to/extracted/three/package]
// Without an argument it runs `npm pack three@VERSION` into a temp dir and extracts it.
import { execFileSync } from 'node:child_process'
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const VERSION = '0.170.0'
const FILES = ['MathUtils', 'Vector3', 'Quaternion', 'Matrix4', 'Euler']
const root = dirname(dirname(fileURLToPath(import.meta.url)))
const out = join(root, 'vendor', 'three-math')

let pkg = process.argv[2]
if (!pkg) {
  const tmp = mkdtempSync(join(tmpdir(), 'three-'))
  execFileSync('npm', ['pack', `three@${VERSION}`, '--silent'], { cwd: tmp, stdio: ['ignore', 'pipe', 'inherit'] })
  execFileSync('tar', ['xzf', `three-${VERSION}.tgz`], { cwd: tmp })
  pkg = join(tmp, 'package')
}
if (JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version !== VERSION) throw new Error(`expected three@${VERSION}`)

mkdirSync(out, { recursive: true })
for (const f of FILES) {
  const src = readFileSync(join(pkg, 'src', 'math', `${f}.js`), 'utf8').replace("from '../constants.js'", "from './constants.js'")
  writeFileSync(join(out, `${f}.js`), src)
}
writeFileSync(join(out, 'constants.js'), '// Stub of three/src/constants.js: only what Matrix4 needs.\nexport const WebGLCoordinateSystem = 2000;\nexport const WebGPUCoordinateSystem = 2001;\n')
writeFileSync(join(out, 'index.js'), `// three@${VERSION} math subset (MIT). Generated by scripts/vendor-three.mjs.\n` + FILES.map((f) => f === 'MathUtils' ? `export * as MathUtils from './MathUtils.js';\n` : `export { ${f} } from './${f}.js';\n`).join(''))
copyFileSync(join(pkg, 'LICENSE'), join(out, 'LICENSE'))
writeFileSync(join(out, 'VERSION'), `three@${VERSION}, files: math/{${FILES.join(',')}}.js; constants.js is a stub\n`)
console.log(`vendored three@${VERSION} -> ${out}`)
