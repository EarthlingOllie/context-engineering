// Bundles graph.ts + LangGraph into one Workflow script: meta literal first, no imports, top-level return last.
// Usage: npm ci && node build.cjs [--minify]   → spike-graph.js
const esbuild = require("esbuild"), fs = require("fs");
// langsmith (pulled in by @langchain/core) imports Node builtins; the Workflow sandbox has none. Tracing is never enabled, so stub them.
const STUBS = {
  "node:os": 'export const homedir=()=>"/";export default {homedir}',
  "node:fs": "export const existsSync=()=>false;export default {}",
  "node:path": 'export const join=(...a)=>a.join("/");export default {join}',
  "node:crypto": 'export const randomUUID=()=>{throw new Error("node:crypto unavailable")};export default {}',
  "node:stream": "export class Duplex{};export default {}",
  "node:worker_threads": "export class Worker{};export default {}",
};
const stub = { name: "stub-node", setup(b) {
  b.onResolve({ filter: /^node:/ }, (a) => ({ path: a.path, namespace: "stub" }));
  b.onLoad({ filter: /.*/, namespace: "stub" }, (a) => ({ contents: STUBS[a.path] ?? "export default {}", loader: "js" }));
} };
const META = `export const meta = {
  name: 'langgraph-spike',
  description: 'Spike: a LangGraph graph (fan-out, then generator-evaluator loop) whose nodes call agent()',
  phases: [{ title: 'Fan-out' }, { title: 'Loop' }],
}
`;
(async () => {
  const r = await esbuild.build({
    entryPoints: ["graph.ts"], bundle: true, format: "iife", globalName: "__lg", platform: "neutral", target: "es2020",
    mainFields: ["browser", "module", "main"], conditions: ["browser", "import", "default"],
    inject: ["clock-shim.js"], plugins: [stub], legalComments: "none", minify: process.argv.includes("--minify"), write: false, logLevel: "error",
  });
  // IIFE: the bundle's top-level names (it declares its own `meta`, `log`, ...) must not collide with the script's meta or the harness globals.
  let js = r.outputFiles[0].text;
  const bad = js.match(/^\s*(import\s*[{*"']|export\s*[{*]|(import|export)\s+(const|let|var|function|class|default)\b).{0,60}/m); if (bad) throw new Error("bundle still has an import or export: " + bad[0]);
  // Date and Math inside the bundle resolve to clock-shim.js via esbuild inject; raw `Date.now(` text that remains is the shim.
  fs.writeFileSync("spike-graph.js", META + "\n// Generated by build.cjs — do not edit.\n" + js + "\nreturn await __lg.runGraph(args, { agent, log });\n");
  console.log("spike-graph.js", fs.statSync("spike-graph.js").size, "bytes");
})().catch((e) => { console.error(e.message); process.exit(1); });
